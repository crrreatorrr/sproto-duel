// Writes src/sim-core/tables.ts: integer lookup tables for the deterministic sim (sin quarter
// wave, CORDIC arctangents). Generated once with float math here; the sim only reads the literals,
// so every engine (Node, browsers, goja) sees identical numbers. Re-run only to change resolution.
import fs from 'node:fs';
const Q = 65536;
const N = 1024; // quarter-wave entries (angle unit: 1/65536 turn, quarter = 16384 units)
const sin = [];
for (let i = 0; i <= N; i++) sin.push(Math.round(Math.sin((i / N) * Math.PI / 2) * Q));
const atan = [];
for (let i = 0; i < 17; i++) atan.push(Math.round((Math.atan(Math.pow(2, -i)) / (2 * Math.PI)) * 65536 * 256));
// CORDIC gain K = prod 1/sqrt(1+2^-2i), Q16.
let k = 1;
for (let i = 0; i < 17; i++) k /= Math.sqrt(1 + Math.pow(2, -2 * i));
const lines = [];
lines.push('// Generated by scripts/gen-sim-tables.mjs. Do not edit by hand.');
lines.push('/* eslint-disable */');
lines.push(`/** sin(i / ${N} * pi/2) in Q16, i = 0..${N}. */`);
lines.push(`export const SIN_Q: readonly number[] = [${sin.join(',')}];`);
lines.push('/** atan(2^-i) in 1/(65536*256) turns, i = 0..16 (CORDIC). */');
lines.push(`export const ATAN_T: readonly number[] = [${atan.join(',')}];`);
lines.push(`/** CORDIC gain 1/K in Q16. */`);
lines.push(`export const CORDIC_K = ${Math.round(k * Q)};`);
fs.writeFileSync(new URL('../src/sim-core/tables.ts', import.meta.url), lines.join('\n') + '\n');
console.log('wrote tables.ts');
