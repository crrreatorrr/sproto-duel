#!/usr/bin/env node
/**
 * Builds dist/duel-sim.server.js: sim-core + replay as one goja-safe ES5 script with top-level
 * globals `DUEL_SIM_VERSION` and `DuelSim`.
 *
 * 1. esbuild bundles src/sim-core/server.ts into an IIFE (`var DuelSim = (() => {...})()`).
 * 2. TypeScript 5's transpiler lowers it to ES5 (classes, let/const, arrows, spread...).
 * 3. The version is sha256 of the BODY (every byte after the first line), first 16 hex digits;
 *    the first line is `var DUEL_SIM_VERSION = '<version>';`.
 *
 * `--check` builds in memory and fails if the committed file differs (CI).
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import ts from 'typescript5';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'dist', 'duel-sim.server.js');

export async function buildBundle() {
  const res = await build({
    entryPoints: [path.join(ROOT, 'src/sim-core/server.ts')],
    bundle: true,
    format: 'iife',
    globalName: 'DuelSim',
    target: 'es2020',
    platform: 'neutral',
    write: false,
    legalComments: 'none',
    charset: 'ascii',
    treeShaking: true,
    logLevel: 'error',
  });
  const es2017 = res.outputFiles[0].text;
  const lowered = ts.transpileModule(es2017, {
    compilerOptions: { target: ts.ScriptTarget.ES5, module: ts.ModuleKind.None, removeComments: false, noEmitHelpers: false, downlevelIteration: false },
    fileName: 'duel-sim.js',
  }).outputText;
  const body = '// Sproto Duel server simulation. Generated by scripts/build-server-sim.mjs from src/sim-core. Do not edit.\n' + lowered.replace(/\r\n/g, '\n');
  const version = crypto.createHash('sha256').update(body, 'utf8').digest('hex').slice(0, 16);
  return { version, text: `var DUEL_SIM_VERSION = '${version}';\n${body}` };
}

/** Split a bundle into its header version and body; recompute the body hash. */
export function parseBundle(text) {
  const nl = text.indexOf('\n');
  const head = text.slice(0, nl);
  const body = text.slice(nl + 1);
  const m = /^var DUEL_SIM_VERSION = '([0-9a-f]{16})';$/.exec(head);
  return { declared: m ? m[1] : null, actual: crypto.createHash('sha256').update(body, 'utf8').digest('hex').slice(0, 16), body };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const { version, text } = await buildBundle();
  if (process.argv.includes('--check')) {
    const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (have !== text) {
      console.error(`dist/duel-sim.server.js is stale: a fresh build gives version ${version}. Run npm run build:server-sim and commit it.`);
      process.exit(1);
    }
    console.log(`dist/duel-sim.server.js is up to date (version ${version})`);
  } else {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, text);
    console.log(`wrote dist/duel-sim.server.js (${text.length} bytes, version ${version})`);
  }
}
